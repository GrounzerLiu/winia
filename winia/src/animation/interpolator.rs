/** 线性插值 (x = x) */
pub fn linear(x: f32) -> f32 { x }

pub trait Interpolator : Sync + Send + std::fmt::Debug {
    fn interpolate(&self, x: f32) -> f32;
}

/// ![image](https://upload.wikimedia.org/wikipedia/commons/0/0e/Linear_interpolation.svg)
#[derive(Debug)]
pub struct Linear {}
impl Default for Linear {
    fn default() -> Self {
        Self::new()
    }
}

impl Linear {
    pub fn new() -> Self {
        Self {}
    }
	pub fn boxed() -> Box<dyn Interpolator> {
		Box::new(Self::new())
	}
}

impl From<Linear> for std::sync::Arc<dyn Interpolator> {
    fn from(i: Linear) -> Self {
        std::sync::Arc::new(i)
    }
}

impl Interpolator for Linear {
    fn interpolate(&self, x: f32) -> f32 {
        x
    }
}

// 使用二分法查找x所在的区间
fn find_interval(points: &Vec<(f32, f32)>, x: f32) -> usize {
    let mut low = 0;
    let mut high = points.len() - 1;

    while high - low > 1 {
        let mid = (low + high) / 2;
        let (x_mid, _) = points[mid];

        if x_mid == x {
            return mid;
        } else if x_mid < x {
            low = mid;
        } else {
            high = mid;
        }
    }
    low
}

macro_rules! interpolator {
    ($name:ident, $map: expr) => {
        #[derive(Debug)]
        pub struct $name {
            points: Vec<(f32, f32)>,
        }
        impl Default for $name {
            fn default() -> Self {
                Self::new()
            }
        }
        impl $name {
            pub fn new() -> Self {
                Self { points: $map }
            }

			pub fn boxed() -> Box<dyn Interpolator> {
				Box::new(Self::new())
			}
        }
        impl From<$name> for std::sync::Arc<dyn Interpolator> {
            fn from(i: $name) -> Self {
                std::sync::Arc::new(i)
            }
        }
        impl Interpolator for $name {
            fn interpolate(&self, x: f32) -> f32 {
                if x < 0.0 {
                    return 0.0;
                } else if x > 1.0 {
                    return 1.0;
                }

                // 查找x所在的区间
                let idx = find_interval(&self.points, x);

                // 计算线性插值
                let (x1, y1) = self.points[idx];
                let (x2, y2) = self.points[idx + 1];
                ((y2 - y1) / (x2 - x1)) * (x - x1) + y1
            }
        }
    };
}

